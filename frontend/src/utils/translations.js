// Helper getter supporting dot notation e.g. t('nav.home')
export function getTranslation(lang, key, fallback = '') {
  const currentLang = translations[lang] || translations.vi;
  const parts = key.split('.');
  let current = currentLang;
  for (const p of parts) {
    if (current && typeof current === 'object' && p in current) {
      current = current[p];
    } else {
      return fallback || key;
    }
  }
  return current || fallback || key;
}
